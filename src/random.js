// A tiny seeded random-number generator (mulberry32) so a screenshot
// staging or a replay can rebuild the exact same field of stars, rocks
// and crates from one seed. Gameplay itself uses an unseeded instance.

export function makeRandom(seed) {
  let state = seed >>> 0;
  return function random() {
    state |= 0;
    state = (state + 0x6d2b79f5) | 0;
    let t = Math.imul(state ^ (state >>> 15), 1 | state);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function pickRandom(rng, list) {
  return list[Math.floor(rng() * list.length)];
}

export function rangeRandom(rng, min, max) {
  return min + rng() * (max - min);
}

// Shuffle a copy of a list in place, Fisher-Yates, using the given rng.
export function shuffle(rng, list) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
